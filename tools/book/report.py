#!/usr/bin/env python3
"""report.md: counts per page / topic / room, unverified hidden-text tokens, errata, OCR artefacts dropped as decor,
the coverage status, and open questions.  Usage: report.py PACK"""
import collections, csv, json, os, re, subprocess, sys

PDF2PRINT = {1: 1147}
for i, p in enumerate(range(1162, 1167)): PDF2PRINT[2 + i] = p
for i, p in enumerate(range(1172, 1177)): PDF2PRINT[7 + i] = p
for i, p in enumerate(range(1198, 1209)): PDF2PRINT[12 + i] = p
ODD = re.compile(r'[0-9].*[a-zăâîșț]|[a-zăâîșț].*[0-9]|[/!{}�•\\|]|[a-zăâîșț][A-ZĂÂÎȘȚ]|^[a-zăâîșț]*[ii]{2}', re.I)


def main(pack):
    J = lambda n: [json.loads(l) for l in open(os.path.join(pack, n), encoding='utf-8')] if os.path.exists(os.path.join(pack, n)) else []
    atoms, facts, items = J('atoms.jsonl'), J('facts.jsonl'), J('items.jsonl')
    scripts = json.load(open(os.path.join(pack, 'scripts.json'), encoding='utf-8'))['scripts'] if os.path.exists(os.path.join(pack, 'scripts.json')) else []
    fx = json.load(open(os.path.join(pack, 'fixes.json'), encoding='utf-8'))
    errata = json.load(open(os.path.join(pack, 'errata.json'), encoding='utf-8')) if os.path.exists(os.path.join(pack, 'errata.json')) else []
    quests = json.load(open(os.path.join(pack, 'gastro-quests.json'), encoding='utf-8'))
    cleaned = open(os.path.join(pack, 'cleaned.txt'), encoding='utf-8').read()
    chk = subprocess.run([sys.executable, '-I', os.path.join(pack, 'check.py'), pack] + (['--topics', ','.join(sorted(set(f['topic'] for f in facts)))] if facts else []),
                         capture_output=True, text=True).stdout
    room_of = {}
    for ch in quests['chapters']:
        for st in ch['steps']:
            room_of[st['topic']] = st['room']
    L = []
    w = L.append
    w('# BOOK-1 report — Gastro.pdf inside the institute map\n')
    w('Generated by `tools/book/report.py`. Every figure below is measured by the build or by `check.py`, not estimated.\n')
    q = os.path.join(pack, 'QUESTIONS.md')
    if os.path.exists(q):
        w('## Questions\n')
        w(open(q, encoding='utf-8').read().strip() + '\n')
    w('## Checker output\n')
    w('```\n' + chk.strip() + '\n```\n')
    # totals
    nonws = sum(1 for c in cleaned if not c.isspace())
    hid_atoms = [a for a in atoms if a['layer'] in ('under_blank', 'mixed')]
    w('## Totals\n')
    w(f'- cleaned.txt: {len(cleaned):,} characters, {nonws:,} non-whitespace; {len(atoms)} atoms; '
      f'{sum(len(a["sent_spans"]) for a in atoms)} sentences')
    w(f'- hidden text (under the white rectangles): {len(hid_atoms)} atoms, '
      f'{sum(len(a["text"]) for a in hid_atoms):,} characters, on PDF pages {sorted(set(a["pdf_page"] for a in hid_atoms))}')
    w(f'- OCR fixes: {len(fx["fixes"])} (+ {len(json.load(open(os.path.join(pack, "rules.json"))))} global rules); '
      f'{sum(1 for f in fx["fixes"] if f.get("status") == "unverified")} of them in hidden text (unverified)')
    w(f'- figures: {len([a for a in atoms if a["kind"] == "figure_caption"])} captions, '
      f'{len([a for a in atoms if a["kind"] == "figure_labels"])} label groups')
    w(f'- facts {len(facts)}, items {len(items)}, scripts {len(scripts)}; topics done: '
      f'{", ".join(sorted(set(f["topic"] for f in facts))) or "none"}\n')
    # per page
    w('## Per page\n')
    w('| PDF | printed | atoms | chars | hidden atoms | fixes | facts |')
    w('|---:|---:|---:|---:|---:|---:|---:|')
    fpage = collections.Counter(f.get('pdf_page') for f in fx['fixes'])
    facts_by_atom = collections.Counter(f['atom'] for f in facts)
    for p in range(1, 23):
        A = [a for a in atoms if a['pdf_page'] == p]
        w(f'| {p} | {PDF2PRINT[p]} | {len(A)} | {sum(len(a["text"]) for a in A):,} | '
          f'{sum(1 for a in A if a["layer"] in ("under_blank", "mixed"))} | {fpage.get(p, 0)} | {sum(facts_by_atom[a["id"]] for a in A)} |')
    # per topic
    w('\n## Per topic and room\n')
    w('| ch | topic | room | atoms | chars | pages | facts | items | scripts |')
    w('|---:|---|---|---:|---:|---|---:|---:|---:|')
    for ch in quests['chapters']:
        for st in ch['steps']:
            t = st['topic']
            A = [a for a in atoms if a['topic'] == t]
            pages = sorted(set(a['page'] for a in A))
            w(f'| {ch["id"]} | {t} | {st["room"]} | {len(A)} | {sum(len(a["text"]) for a in A):,} | '
              f'{pages[0] if pages else ""}{"–" + str(pages[-1]) if len(pages) > 1 else ""} | '
              f'{sum(1 for f in facts if f["topic"] == t)} | {sum(1 for i in items if i["topic"] == t)} | {sum(1 for s in scripts if s["topic"] == t)} |')
    # hidden words per page + cross-check against the white rectangles
    w('\n## Hidden text: words per page\n')
    hc = os.path.join(pack, '..', 'build', 'hiddencheck.json')
    pages_w = json.load(open(os.path.join(pack, '..', 'src', 'words.json'), encoding='utf-8'))
    wo = os.path.join(pack, '..', 'src', 'white_overlays.json')
    white = {int(k): v for k, v in json.load(open(wo)).items()} if os.path.exists(wo) else {}
    tot_h = 0
    for P in pages_w:
        n = sum(1 for B in P['blocks'] for L_ in B['lines'] for x in L_['words'])
        hcount = 0
        for B in P['blocks']:
            for L_ in B['lines']:
                for x in L_['words']:
                    cx, cy = (x['bbox'][0] + x['bbox'][2]) / 2, (x['bbox'][1] + x['bbox'][3]) / 2
                    if x['ink'] == 0 or any(a0 <= cx <= c0 and b0 <= cy <= d0 for a0, b0, c0, d0 in white.get(P['pdf_page'], [])):
                        hcount += 1
        if hcount:
            tot_h += hcount
            w(f'- PDF page {P["pdf_page"]} (printed {PDF2PRINT[P["pdf_page"]]}): {hcount} hidden words of {n}')
    w(f'- total: {tot_h} hidden words')
    if os.path.exists(hc):
        H = json.load(open(hc, encoding='utf-8'))
        w(f'- cross-check against the white rectangles of the PDF: hidden words outside a white rectangle = '
          f'{len(H["hidden_outside_overlay"])} (no word with visible ink is classed as hidden); words under a white rectangle '
          f'that carry ink = {len(H["inked_inside_overlay"])} ' + ', '.join(f'`{x[1]}` (PDF {x[0]})' for x in H['inked_inside_overlay'])
          + ' — ink from an overlapping icon; classed hidden by the build')
    # items per fact, exam coverage
    cov = os.path.join(pack, 'coverage.json')
    if os.path.exists(cov):
        C = json.load(open(cov, encoding='utf-8'))
        w('\n## Items per fact (tested facts only) and exam coverage\n')
        w('| topic | facts | min items / fact | median items / fact |')
        w('|---|---:|---:|---:|')
        for t, v in sorted(C.get('topics', {}).items()):
            w(f'| {t} | {v["facts"]} | {v["min_items_per_fact"]} | {v["median_items_per_fact"]} |')
        ne = C.get('no_exam_item', [])
        w(f'\nFacts without a simplu / multiplu item (no four wrong options in page, section or topic): {len(ne)}')
        for fid, why in ne:
            w(f'- {fid}: {why}')
    # unverified tokens
    w('\n## Hidden text: unverified OCR\n')
    w('This text cannot be checked against the page image. Changes made from the word itself (marked unverified):\n')
    w('| PDF | find | replace | why |')
    w('|---:|---|---|---|')
    for f in fx['fixes']:
        if f.get('status') == 'unverified':
            w(f'| {f.get("pdf_page")} | `{f["find"]}` | `{f["replace"]}` | {f.get("why", "")} |')
    w('\nOther tokens in hidden text that look doubtful (odd characters; machine list, see also the per-page notes):\n')
    toks = collections.OrderedDict()
    for a in hid_atoms:
        for tok in re.findall(r'\S+', a['text']):
            t = tok.strip('.,;:()„”"')
            if t and ODD.search(t) and not re.fullmatch(r'[\d.,–%<>=]+', t):
                toks.setdefault(t, a['id'])
    w(', '.join(f'`{t}` ({aid})' for t, aid in toks.items()) or 'none')
    # errata
    w('\n## Errata (taught as printed, items flagged needs_review)\n')
    for e in errata:
        w(f'- **{e["id"]}** p. {e["page"]}: {e["printed"]} — {e["issue"]}')
    # decor
    w('\n## OCR artefacts that are not text (consumed as decor, not taught)\n')
    for d in fx.get('decor', []):
        w(f'- PDF {d["pdf_page"]} `{d["text"][:60]}` — {d["why"]}')
    # notes
    w('\n## Per-page notes (from proofreading)\n')
    nd = os.path.join(pack, 'notes')
    for fn in sorted(os.listdir(nd)):
        w(f'\n### {fn}\n')
        w(re.sub(r'^(#+)', r'###\1', open(os.path.join(nd, fn), encoding='utf-8').read().strip(), flags=re.M))
    open(os.path.join(pack, 'report.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('report.md written')


if __name__ == '__main__':
    main(sys.argv[1])
