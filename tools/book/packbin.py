#!/usr/bin/env python3
"""Compile the content pack into one binary file for the engine (build time): fixed-size little-endian records,
strings in one UTF-8 table addressed by u32 offsets, no JSON at run time.

  packbin.py PACK OUT.mgpack        -> also writes OUT.mgpack.h (the C structs) next to it

Layout: header (16 table descriptors {u32 offset, u32 count, u32 record_size}), then the tables, each 8-byte aligned.
Tables: strings, rooms, topics, atoms, facts, items, opts, refs, scripts, steps, props, slots.
"""
import json, os, struct, sys, re

MAGIC = b'MGPK'
VERSION = 3
ITEM_TYPES = ['simplu', 'multiplu', 'card', 'cloze', 'sort', 'match', 'order', 'label']
SCRIPT_KINDS = ['station', 'case', 'inspect', 'dispense', 'read', 'sequence', 'sort', 'directory', 'colleague', 'round', 'garda', 'exam']
ATOM_KINDS = ['heading', 'paragraph', 'list_item', 'box_row', 'table_row', 'figure_caption', 'figure_labels', 'contents_line',
              'reference', 'running_header', 'byline']
FACT_TYPES = ['statement', 'number', 'dose', 'name', 'definition', 'cause', 'sign', 'indication', 'contraindication', 'sequence',
              'comparison', 'exception', 'set', 'member', 'structure', 'label', 'reference', 'example', 'detail', 'epidemiology',
              'role', 'other']
STAGES = ['predict', 'teach', 'check']
TABLES = ['strings', 'rooms', 'topics', 'atoms', 'facts', 'items', 'opts', 'refs', 'scripts', 'steps', 'props', 'slots', 'figlabels', 'furniture']

C_HEADER = r'''/* generated by tools/book/packbin.py — the BOOK-1 content pack (.mgpack), little-endian, 8-byte aligned tables */
#ifndef MG_PACK_FORMAT_H
#define MG_PACK_FORMAT_H
#include <stdint.h>
#define MGPK_MAGIC 0x4B50474Du /* "MGPK" */
#define MGPK_VERSION 3u
enum { MGPK_STRINGS, MGPK_ROOMS, MGPK_TOPICS, MGPK_ATOMS, MGPK_FACTS, MGPK_ITEMS, MGPK_OPTS, MGPK_REFS, MGPK_SCRIPTS,
       MGPK_STEPS, MGPK_PROPS, MGPK_SLOTS, MGPK_FIGLABELS, MGPK_FURNITURE, MGPK_TABLE_COUNT };
typedef struct mgpk_table_t { uint32_t offset, count, size; } mgpk_table_t;
typedef struct mgpk_header_t { uint32_t magic, version, fact_count, item_count; mgpk_table_t table[16]; } mgpk_header_t;
typedef struct mgpk_room_t { uint32_t id, name; int8_t floor; uint8_t pad[3]; float x0, z0, x1, z1; } mgpk_room_t;            /* 28 */
typedef struct mgpk_topic_t { uint32_t id, title; uint16_t room, chapter, step, flags;
                              uint32_t first_fact, fact_count, first_item, item_count, first_script, script_count; } mgpk_topic_t; /* 40 */
typedef struct mgpk_atom_t { uint32_t id, text; uint16_t page, topic; uint8_t kind, layer, frag, pad; uint32_t fig; } mgpk_atom_t; /* 20 */
typedef struct mgpk_fact_t { uint32_t id, claim, atom; uint16_t topic, page; uint8_t type, flags, pad[2]; } mgpk_fact_t;      /* 20 */
enum { MGPK_FACT_NEEDS_REVIEW = 1, MGPK_FACT_UNVERIFIED_OCR = 2 };
typedef struct mgpk_item_t { uint32_t id, stem, explanation, review_note; uint16_t topic; uint8_t type, flags, difficulty, n_opts, n_facts, n_extra;
                             uint32_t first_opt, first_fact_ref, first_extra_ref, correct_mask; } mgpk_item_t;              /* 40 */
enum { MGPK_ITEM_NEEDS_REVIEW = 1, MGPK_ITEM_UNVERIFIED_OCR = 2, MGPK_ITEM_LIST_GAP = 4 };
/* opts: simplu / multiplu options (ok = correct), cloze answers, card answer, sort / match / label entries, order steps */
typedef struct mgpk_opt_t { uint32_t text, aux, why, fact; uint8_t ok, group, pad[2]; } mgpk_opt_t;                         /* 20 */
/* a required script longer than 15 steps is stored as parts 1..parts on the same prop / NPC; unsplit = 1 of 1 */
typedef struct mgpk_script_t { uint32_t id, title; uint16_t topic, room; uint8_t kind, required, part, parts;
                               uint32_t prop, slot, npc, first_step, step_count; } mgpk_script_t;                         /* 36 */
/* step flags: 1 = a teach step shown again at the start of a later part (a new sitting) */
typedef struct mgpk_step_t { uint8_t stage, flags; uint16_t n_atoms; uint32_t item, first_atom_ref; } mgpk_step_t;             /* 12 */
/* furniture = row of the furniture table this prop / NPC point is (on_model: the model's own podium, shelf, chair ...), or 0xFFFF */
typedef struct mgpk_prop_t { uint32_t id, kind, label; uint16_t room, furniture; int8_t floor; uint8_t pad; uint16_t yaw; float x, z; } mgpk_prop_t; /* 28 */
/* every piece of furniture of institute.map (prop records): x z = footprint centre (door leaf: the hinge), w across the facing
   direction, d along it, h height; mount 0 free, 1 wall, 2 floor (walked on), 3 door leaf (opens towards open_x, open_z) */
typedef struct mgpk_furniture_t { uint32_t id, kind; uint16_t room; int8_t floor; uint8_t mount; uint16_t yaw; int8_t open_x, open_z; float x, z, w, d, h; } mgpk_furniture_t; /* 36 */
enum { MGPK_MOUNT_FREE, MGPK_MOUNT_WALL, MGPK_MOUNT_FLOOR, MGPK_MOUNT_DOOR };
typedef mgpk_prop_t mgpk_slot_t;                                                                              /* 28; label = MGPK_NONE */
/* figure labels for `label` items: box in pixels of the 200-dpi crop fig/<fig>.png (crop size w x h) */
typedef struct mgpk_figlabel_t { uint32_t fig, text; uint16_t x0, y0, x1, y1, w, h; } mgpk_figlabel_t;                      /* 20 */
#define MGPK_NONE 0xFFFFFFFFu
#endif
'''


class StrTab:
    def __init__(self):
        self.buf = bytearray(b'\0')
        self.idx = {'': 0}

    def __call__(self, s):
        if s is None:
            return 0xFFFFFFFF
        if s not in self.idx:
            self.idx[s] = len(self.buf)
            self.buf += s.encode('utf-8') + b'\0'
        return self.idx[s]


def main(pack, out):
    J = lambda n: [json.loads(l) for l in open(os.path.join(pack, n), encoding='utf-8')]
    atoms, facts, items = J('atoms.jsonl'), J('facts.jsonl'), J('items.jsonl')
    scripts = [x for x in json.load(open(os.path.join(pack, 'scripts.json'), encoding='utf-8'))['scripts'] if x.get('topic')]
    quests = json.load(open(os.path.join(pack, 'gastro-quests.json'), encoding='utf-8'))
    mp = open(os.path.join(pack, 'institute.map'), encoding='utf-8').read()
    S = StrTab()
    rooms = []
    for m in re.finditer(r'^room\s+(-?\d+)\s+(\S+)\s+\S+\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+"([^"]*)"', mp, re.M):
        rooms.append((m.group(2), int(m.group(1)), *[float(m.group(i)) for i in (3, 4, 5, 6)], m.group(7)))
    room_ix = {r[0]: i for i, r in enumerate(rooms)}
    props = [m.groups() for m in re.finditer(r'^iprop\s+(-?\d+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+"([^"]*)"', mp, re.M)]
    slots = [m.groups() for m in re.finditer(r'^islot\s+(-?\d+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)', mp, re.M)]
    furn = [m.groups() for m in re.finditer(r'^prop\s+(-?\d+)\s+(\S+)\s+(\S+\.\d+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(wall|free|floor|door)(?:\s+opens\s+(\S+)\s+(\S+))?', mp, re.M)]
    furn_ix = {f[2]: i for i, f in enumerate(furn)}
    onm = dict(re.findall(r'^i(?:prop|slot)\s+-?\d+\s+\S+\s+(\S+)\s.*\son_model\s+(\S+)\s*$', mp, re.M))
    order = [st['topic'] for ch in quests['chapters'] for st in ch['steps']]
    tinfo = {st['topic']: (ch['id'], i, st) for ch in quests['chapters'] for i, st in enumerate(ch['steps'])}
    topic_ix = {t: i for i, t in enumerate(order)}
    atom_ix = {a['id']: i for i, a in enumerate(atoms)}
    facts.sort(key=lambda f: (topic_ix[f['topic']], f['id']))
    items.sort(key=lambda i: (topic_ix[i['topic']], i['id']))
    scripts.sort(key=lambda s: (topic_ix[s['topic']], s['id']))
    fact_ix = {f['id']: i for i, f in enumerate(facts)}
    item_ix = {it['id']: i for i, it in enumerate(items)}
    prop_ix = {p[2]: i for i, p in enumerate(props)}
    slot_ix = {p[2]: i for i, p in enumerate(slots)}
    T = {k: bytearray() for k in TABLES}
    cnt = {k: 0 for k in TABLES}

    def put(tab, fmt, *v):
        T[tab] += struct.pack('<' + fmt, *v)
        cnt[tab] += 1

    for r in rooms:
        put('rooms', 'IIb3x4f', S(r[0]), S(r[6]), r[1], r[2], r[3], r[4], r[5])
    for t in order:
        ch, step, st = tinfo[t]
        fs = [i for i, f in enumerate(facts) if f['topic'] == t]
        its = [i for i, x in enumerate(items) if x['topic'] == t]
        scs = [i for i, x in enumerate(scripts) if x['topic'] == t]
        put('topics', 'IIHHHHIIIIII', S(t), S(st['title']), room_ix.get(st['room'], 0xFFFF), ch, step, 0,
            fs[0] if fs else 0, len(fs), its[0] if its else 0, len(its), scs[0] if scs else 0, len(scs))
    for a in atoms:
        put('atoms', 'IIHHBBBxI', S(a['id']), S(a['text']), a['page'], topic_ix.get(a['topic'], 0xFFFF),
            ATOM_KINDS.index(a['kind']), {'visible': 0, 'under_blank': 1, 'mixed': 2, 'image_only': 3}[a['layer']],
            {None: 0, 'start': 1, 'end': 2, 'both': 3}[a['fragment']], S(a.get('fig')) if a.get('fig') else 0xFFFFFFFF)
    for f in facts:
        fl = (1 if f.get('needs_review') else 0) | (2 if f.get('unverified_ocr') else 0)
        put('facts', 'IIIHHBB2x', S(f['id']), S(f['claim']), atom_ix[f['atom']], topic_ix[f['topic']], f['page'],
            FACT_TYPES.index(f['type']) if f['type'] in FACT_TYPES else FACT_TYPES.index('other'), fl)
    for it in items:
        first_opt = cnt['opts']
        mask = 0
        opts = []
        if it['type'] in ('simplu', 'multiplu'):
            for k, o in enumerate(it['options']):
                opts.append((o['t'], None, o.get('why'), o.get('fact') or o.get('from_fact'), 1 if o.get('ok') else 0, 0))
                if o.get('ok'):
                    mask |= 1 << k
        elif it['type'] == 'cloze':
            opts = [(a, None, None, None, 1, 0) for a in it['answers']]
        elif it['type'] == 'card':
            opts = [(it['answer'], None, None, None, 1, 0)]
        elif it['type'] == 'sort':
            opts = [(e['t'], None, None, e['fact'], 1, it['groups'].index(e['group'])) for e in it['entries']]
            opts += [(g, None, None, None, 0, 255) for g in it['groups']]
        elif it['type'] == 'match':
            opts = [(p['left'], p['right'], None, p['fact'], 1, 0) for p in it['pairs']]
        elif it['type'] == 'order':
            opts = [(s, None, None, None, 1, k) for k, s in enumerate(it['sequence'])]
        elif it['type'] == 'label':
            opts = [(l['t'], it['figure'], None, l['fact'], 1, 0) for l in it['labels']]
        for t, aux, why, fid, ok, grp in opts:
            put('opts', 'IIIIBB2x', S(t), S(aux) if aux else 0xFFFFFFFF, S(why) if why else 0xFFFFFFFF,
                fact_ix.get(fid, 0xFFFFFFFF) if fid else 0xFFFFFFFF, ok, grp)
        first_ref = cnt['refs']
        for fid in it['fact_ids']:
            put('refs', 'I', fact_ix[fid])
        fl = (1 if 'needs_review' in it['flags'] else 0) | (2 if 'unverified_ocr' in it['flags'] else 0) | (4 if it.get('list_gap') else 0)
        put('items', 'IIIIHBBBBBBIIII', S(it['id']), S(it['stem']), S(it['explanation']), S(it.get('review_note')) if it.get('review_note') else 0xFFFFFFFF,
            topic_ix[it['topic']], ITEM_TYPES.index(it['type']), fl, it.get('difficulty', 2), len(opts), len(it['fact_ids']), 0,
            first_opt, first_ref, 0xFFFFFFFF, mask)
    for sc in scripts:
        first_step = cnt['steps']
        for st in sc['steps']:
            if st['stage'] == 'teach':
                r0 = cnt['refs']
                for aid in st['atoms']:
                    put('refs', 'I', atom_ix[aid])
                put('steps', 'BBHII', STAGES.index('teach'), 1 if st.get('repeat') else 0, len(st['atoms']), 0xFFFFFFFF, r0)
            else:
                put('steps', 'BxHII', STAGES.index(st['stage']), 0, item_ix[st['item']], 0xFFFFFFFF)
        put('scripts', 'IIHHBBBBIIIII', S(sc['id']), S(sc['title']), topic_ix[sc['topic']], room_ix[sc['room']],
            SCRIPT_KINDS.index(sc['kind']), 1 if sc.get('required') else 0, sc.get('part', 1), sc.get('parts', 1),
            prop_ix.get(sc.get('prop'), 0xFFFFFFFF), slot_ix.get(sc.get('slot'), 0xFFFFFFFF), S(sc.get('npc')) if sc.get('npc') else 0xFFFFFFFF,
            first_step, cnt['steps'] - first_step)
    for p in props:
        fl, room, pid, model, x, z, yaw, label = p
        put('props', 'IIIHHbxHff', S(pid), S(model), S(label), room_ix[room], furn_ix[onm[pid]] if pid in onm else 0xFFFF, int(fl), int(float(yaw)) % 360, float(x), float(z))
    for p in slots:
        fl, room, sid, kind, x, z, yaw = p
        put('slots', 'IIIHHbxHff', S(sid), S(kind), 0xFFFFFFFF, room_ix[room], furn_ix[onm[sid]] if sid in onm else 0xFFFF, int(fl), int(float(yaw)) % 360, float(x), float(z))
    for fl, room, fid, kind, x, z, yaw, w, d, h, mount, ox, oz in furn:
        put('furniture', 'IIHbBHbbfffff', S(fid), S(kind), room_ix.get(room, 0xFFFF), int(fl), ['free', 'wall', 'floor', 'door'].index(mount),
            int(float(yaw)) % 360, int(float(ox or 0)), int(float(oz or 0)), float(x), float(z), float(w), float(d), float(h))
    figs = json.load(open(os.path.join(pack, 'fig', 'figures.json'), encoding='utf-8'))
    from PIL import Image
    for f in figs:
        w, h = Image.open(os.path.join(pack, f['file'])).size
        for l in f.get('labels', []):
            b = l['bbox'] or [0, 0, 0, 0]
            put('figlabels', 'IIHHHHHH', S(f['id']), S(l['t']), *[max(0, min(65535, int(v))) for v in b], w, h)
    T['strings'] = S.buf
    cnt['strings'] = len(S.buf)
    sizes = {'strings': 1, 'rooms': 28, 'topics': 40, 'atoms': 20, 'facts': 20, 'items': 40, 'opts': 20, 'refs': 4,
             'scripts': 36, 'steps': 12, 'props': 28, 'slots': 28, 'figlabels': 20, 'furniture': 36}
    for k in TABLES:
        if k != 'strings':
            assert len(T[k]) == cnt[k] * sizes[k], (k, len(T[k]), cnt[k], sizes[k])
    hdr_size = 16 + 16 * 12
    body = bytearray()
    descs = []
    off = hdr_size
    for k in TABLES:
        pad = (-off) % 8
        body += b'\0' * pad
        off += pad
        descs.append((off, cnt[k], sizes[k]))
        body += T[k]
        off += len(T[k])
    hdr = struct.pack('<4sIII', MAGIC, VERSION, len(facts), len(items))
    for d in descs + [(0, 0, 0)] * (16 - len(descs)):
        hdr += struct.pack('<III', *d)
    data = hdr + body
    open(out, 'wb').write(data)
    open(out + '.h', 'w').write(C_HEADER)
    print(f'{out}: {len(data):,} bytes; ' + ', '.join(f'{k} {cnt[k]}' for k in TABLES)
          + f'; progress bitset {(len(facts) + 7) // 8} bytes per account')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
