#!/usr/bin/env python3
"""Compile authored topics into the pack: facts.jsonl, items.jsonl, scripts.json, institute.map (+ iprop records).

  compile.py PACK [topic ...]     (no topic = every module in tools/book/topics/)
Topic modules are re-run only when named (or when no topic is named); the merge always reads every PACK/topics/*.json.
"""
import importlib.util, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from content import Topic  # noqa: E402

MAP_MARK = '# ---- BOOK-1 interaction props (generated by tools/book/compile.py; scripts.json refers to them by id) ----'


def run_topic(pack, name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, 'topics', name + '.py'))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    T = Topic(name, pack)
    m.build(T)
    nf, ni, ns, weak, noexam = T.save()
    print(f'{name}: {nf} facts, {ni} items, {ns} scripts' + (f'; facts tested by < 2 item types: {weak}' if weak else '')
          + (f'; facts with no exam item: {noexam}' if noexam else ''))


def review_scripts(pack):
    """Optional review content (never counts toward coverage): pools drawn at run time from the items of finished rooms.
    Counts and scoring of the final simulation are the author's to set (not hard-coded)."""
    q = json.load(open(os.path.join(pack, 'gastro-quests.json'), encoding='utf-8'))
    out = []
    for ch in q['chapters']:
        if ch['id'] == 0:
            continue
        out.append({'id': f'r-comisie-ch{ch["id"]}', 'topic': None, 'room': 'o_comisie', 'kind': 'exam', 'required': False,
                    'title': ch.get('boss') or f'Comisia: capitolul {ch["id"]}', 'trigger': 'interact', 'slot': 'table',
                    'opens_when': f'every room of chapter {ch["id"]} complete',
                    'pool': {'chapters': [ch['id']], 'types': ['simplu', 'multiplu'], 'count': 'set by the author'},
                    'steps': [], 'covers': []})
    out.append({'id': 'r-round', 'topic': None, 'room': 'w_statie', 'kind': 'round', 'required': False,
                'title': 'Vizita în secție: recapitulare', 'trigger': 'interact', 'slot': 'post',
                'pool': {'chapters': 'completed rooms', 'types': 'all', 'spacing': 'facts answered longest ago first'},
                'steps': [], 'covers': []})
    out.append({'id': 'r-garda', 'topic': None, 'room': 'g_garda', 'kind': 'garda', 'required': False,
                'title': 'Garda: cazuri din toate capitolele terminate', 'trigger': 'interact', 'slot': 'desk',
                'pool': {'chapters': 'completed rooms', 'types': ['simplu', 'multiplu', 'card'], 'rooms': ['g_bay1', 'g_bay2', 'g_bay3', 'g_bay4', 'g_bay5', 'g_bay6']},
                'steps': [], 'covers': []})
    out.append({'id': 'r-examen', 'topic': None, 'room': 'o_examen', 'kind': 'exam', 'required': False,
                'title': 'Sala de examen: simulare', 'trigger': 'interact', 'slot': 'desk',
                'opens_when': 'every chapter exam passed',
                'pool': {'chapters': [1, 2, 3, 4], 'types': ['simplu', 'multiplu'], 'count': 'set by the author', 'scoring': 'set by the author'},
                'steps': [], 'covers': []})
    return out


def merge(pack):
    tdir = os.path.join(pack, 'topics')
    facts, items, scripts, props, slots, exempt = [], [], [], [], [], {}
    for fn in sorted(os.listdir(tdir)):
        if fn.endswith('.json'):
            d = json.load(open(os.path.join(tdir, fn), encoding='utf-8'))
            facts += d['facts']; items += d['items']; scripts += d['scripts']; props += d['props']
            slots += d.get('slots', []); exempt.update(d.get('exam_exempt', {}))
    scripts += review_scripts(pack)
    with open(os.path.join(pack, 'facts.jsonl'), 'w', encoding='utf-8') as f:
        for x in facts:
            f.write(json.dumps(x, ensure_ascii=False) + '\n')
    with open(os.path.join(pack, 'items.jsonl'), 'w', encoding='utf-8') as f:
        for x in items:
            f.write(json.dumps(x, ensure_ascii=False) + '\n')
    json.dump({'version': 1, 'pack': 'gastro', 'map': 'institute',
               'rules': {'room_complete': 'every fact of the room\'s topics answered correctly at least once',
                         'chapter_exam_opens': 'when every room of the chapter is complete',
                         'coverage_counts': 'required scripts only; optional and review scripts never count'},
               'scripts': scripts}, open(os.path.join(pack, 'scripts.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    # map: source map + generated iprop section
    src = open(os.path.join(pack, '..', 'src', 'institute.map'), encoding='utf-8').read().split(MAP_MARK)[0].rstrip('\n')
    lines = [src, '', MAP_MARK,
             '# iprop <floor> <room> <id> <kind> <x> <z> <yaw> "<label>"    an interactable prop (instanced per kind); yaw 0 faces +z / south',
             '# islot <floor> <room> <id> <kind> <x> <z> <yaw>             a named interaction point (NPC stand / seat) used by scripts',
             '# a trailing on_model = the institute model already has this piece of furniture there (its podium, shelf, poster, chair): no new mesh',
             '# prop kinds (prop_kinds.json; w x d metres across x along the facing direction; wall = flush against a wall):']
    PK = json.load(open(os.path.join(pack, 'prop_kinds.json'), encoding='utf-8'))
    for k, v in PK['kinds'].items():
        lines.append(f'#   {k:12s} {v["w"]:.2f} x {v["d"]:.2f}  {v["mount"]:4s}  {v["status"]:8s}  {v["desc"]}')
    for p in props:
        if p['model'] not in PK['model_to_kind']:
            raise SystemExit(f'prop {p["id"]}: model {p["model"]} has no kind in prop_kinds.json')
        p['kind'] = PK['model_to_kind'][p['model']]
    rooms = []
    for p in props + slots:
        if p['room'] not in rooms:
            rooms.append(p['room'])
    for r in rooms:
        P = [p for p in props if p['room'] == r]
        S = [p for p in slots if p['room'] == r]
        tops = sorted(set(p['topic'] for p in P + S))
        lines.append(f'# room {r} ({", ".join(tops)}): {len(P)} props, {len(S)} slots')
        for p in P:
            lines.append(f'iprop {p["floor"]} {p["room"]} {p["id"]} {p["kind"]} {p["x"]} {p["z"]} {p["yaw"]} "{p["label"]}"' + (' on_model' if p.get('on_model') else ''))
        for p in S:
            lines.append(f'islot {p["floor"]} {p["room"]} {p["id"]} {p["kind"]} {p["x"]} {p["z"]} {p["yaw"]}' + (' on_model' if p.get('on_model') else ''))
    open(os.path.join(pack, 'institute.map'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    json.dump(exempt, open(os.path.join(pack, 'exam_exempt.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    # lock: the atom text every fact / item was written against (check.py lists what changed since)
    import hashlib
    atoms = [json.loads(l) for l in open(os.path.join(pack, 'atoms.jsonl'), encoding='utf-8')]
    json.dump({a['id']: hashlib.sha1(a['text'].encode('utf-8')).hexdigest()[:16] for a in atoms},
              open(os.path.join(pack, 'atoms.lock.json'), 'w'), indent=0)
    print(f'merged: {len(facts)} facts, {len(items)} items, {len(scripts)} scripts, {len(props)} new props, {len(slots)} new slots')


if __name__ == '__main__':
    pack = sys.argv[1]
    args = [a for a in sys.argv[2:] if not a.startswith('--')]
    names = args or [f[:-3] for f in sorted(os.listdir(os.path.join(HERE, 'topics'))) if f.endswith('.py') and not f.startswith('_')]
    for n in names:
        run_topic(pack, n)
    if '--no-merge' not in sys.argv:
        merge(pack)
